/**
 * Atomically takes ownership of a build. Two schedulers (a queued batch and a
 * manual retry) can otherwise build the same course twice and spend free-model
 * quota on a duplicate map.
 */
export const claimBuild = internalMutation({
  args: { courseId: v.id("courses") },
  handler: async (ctx, { courseId }) => {
    const course = await ctx.db.get(courseId);
    if (!course || course.status === "ready") return { claimed: false };

    const now = Date.now();
    const running =
      course.status === "processing" &&
      course.processingStartedAt !== undefined &&
      now - course.processingStartedAt < 10 * 60 * 1000;
    if (running) return { claimed: false };

    await ctx.db.patch(courseId, {
      status: "processing",
      progress: "Mapping the specification…",
      errorMessage: undefined,
      processingStartedAt: now,
      updatedAt: now,
    });
    return { claimed: true };
  },
});

export const completeBuild = internalMutation({
  args: {
    courseId: v.id("courses"),
    pathway: v.object({
      overview: v.string(),
      examFormat: v.string(),
      source: v.optional(
        v.union(
          v.literal("savemyexams"),
          v.literal("cognito"),
          v.literal("bluprint"),
          v.literal("rs"),
        ),
      ),
      sourceUrl: v.optional(v.string()),
      cognitoSyncedAt: v.optional(v.number()),
      version: v.optional(v.number()),
      papers: v.optional(
        v.array(
          v.object({
            label: v.string(),
            topicIds: v.array(v.string()),
          }),
        ),
      ),
      units: v.array(
        v.object({
          title: v.string(),
          summary: v.string(),
          topics: v.array(
            v.object({
              id: v.string(),
              title: v.string(),
              specReference: v.optional(v.string()),
              summary: v.string(),
              keyPoints: v.array(v.string()),
              examSkill: v.string(),
            }),
          ),
        }),
      ),
    }),
  },
  handler: async (ctx, { courseId, pathway }) => {
    const course = await ctx.db.get(courseId);
    if (!course) throw new Error("Course not found.");

    // Preserve tick-offs across a rebuild by matching topic titles, not
    // positional ids — a regenerated map may reorder units.
    const completed = new Set(course.completedTopics);
    const completedTitles = new Set(
      (course.pathway?.units ?? [])
        .flatMap((unit) => unit.topics)
        .filter((topic) => completed.has(topic.id))
        .map((topic) => topic.title.trim().toLowerCase()),
    );
    const preserved = pathway.units
      .flatMap((unit) => unit.topics)
      .filter((topic) => completedTitles.has(topic.title.trim().toLowerCase()))
      .map((topic) => topic.id);

    // Topic ids are assigned by the rebuild, so cached Cognito text for the old
    // ids is dropped rather than shown against the wrong topic.
    const cachedNotes = await ctx.db
      .query("cognitoTopicNotes")
      .withIndex("by_course_topic", (q) => q.eq("courseId", courseId))
      .collect();
    for (const row of cachedNotes) await ctx.db.delete(row._id);
    const cachedPapers = await ctx.db
      .query("cognitoPastPapers")
      .withIndex("by_course", (q) => q.eq("courseId", courseId))
      .collect();
    for (const row of cachedPapers) await ctx.db.delete(row._id);

    await ctx.db.patch(courseId, {
      pathway,
      completedTopics: preserved,
      status: "ready",
      progress: undefined,
      errorMessage: undefined,
      processingStartedAt: undefined,
      updatedAt: Date.now(),
    });
  },
});

