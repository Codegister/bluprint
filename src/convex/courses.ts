/**
 * Course pathways: the second way into Bluprint.
 *
 * A student picks a level, exam board and several subjects. Each course is
 * stored immediately as `queued`, then a scheduled action maps the
 * specification with a larger model. The page subscribes to the course row, so
 * every pathway appears as it finishes without the browser holding a request
 * open.
 */

/** Short, boring text fields used by courses. */
function safeCourseLabel(value?: string): string | undefined {
  if (!value) return undefined;
  const trimmed = value.replace(/\x00/g, "").trim();
  return trimmed.length > 0 ? trimmed.slice(0, 80) : undefined;
}

const MAX_COURSES_PER_SETUP = 12;

// Keep topic ids and counts where they already are; the syllabus is untrusted
// text, but ids are generated by the server, not the browser.
function topicIds(pathway: { units: Array<{ topics: Array<{ id: string }> }> } | undefined) {
  if (!pathway) return new Set<string>();
  return new Set(pathway.units.flatMap((unit) => unit.topics.map((topic) => topic.id)));
}

function countTopics(pathway: { units: Array<{ topics: Array<unknown> }> } | undefined) {
  if (!pathway) return 0;
  return pathway.units.reduce((sum, unit) => sum + unit.topics.length, 0);
}

function normalizeLevel(value: string): string | undefined {
  const trimmed = value.replace(/\x00/g, "").trim();
  return trimmed.length > 0 ? trimmed.slice(0, 40) : undefined;
}

/** A build that never started, or one that stopped part-way through. */
const QUEUED_STALE_MS = 2 * 60 * 1000;
const PROCESSING_STALE_MS = 10 * 60 * 1000;

function buildStalled(
  course: { status: string; processingStartedAt?: number; updatedAt: number },
  now: number,
): boolean {
  if (course.status === "processing") {
    return (
      course.processingStartedAt === undefined ||
      now - course.processingStartedAt > PROCESSING_STALE_MS
    );
  }
  // A queue row is picked up within seconds. One that is still queued minutes
  // later means its scheduled action was lost (an interrupted deploy, a
  // scheduler failure), so it needs to be queued again rather than left to sit
  // at "Mapping specification" forever.
  if (course.status === "queued") return now - course.updatedAt > QUEUED_STALE_MS;
  return false;
}

/** The main screen's course table: one row per qualification, with progress. */
export const listMine = query({
  args: {},
  handler: async (ctx) => {
    const userId = await requireUserId(ctx);
    const [courses, sets] = await Promise.all([
      ctx.db
        .query("courses")
        .withIndex("by_user_updated", (q) => q.eq("userId", userId))
        .order("desc")
        .collect(),
      ctx.db
        .query("studySets")
        .withIndex("by_user_updated", (q) => q.eq("userId", userId))
        .collect(),
    ]);

    const now = Date.now();
    return courses.map((course) => {
      const linked = sets.filter((set) => set.courseId === course._id);
      const ids = topicIds(course.pathway);
      const completedCount = course.completedTopics.filter((id) => ids.has(id)).length;
      const cardCount = linked.reduce((sum, set) => sum + set.cardCount, 0);
      const knownCount = linked.reduce((sum, set) => sum + set.knownCount, 0);
      return {
        _id: course._id,
        subject: course.subject,
        level: course.level,
        examBoard: course.examBoard,
        tier: course.tier,
        variant: course.variant,
        poetryTheme: course.poetryTheme,
        status: course.status,
        progress: course.progress,
        errorMessage: course.errorMessage,
        processingStartedAt: course.processingStartedAt,
        topicCount: countTopics(course.pathway),
        completedCount,
        unitCount: course.pathway?.units.length ?? 0,
        setCount: linked.length,
        cardCount,
        knownCount,
        createdAt: course.createdAt,
        updatedAt: course.updatedAt,
        lastStudiedAt: course.lastStudiedAt,
        isNew: now - course.createdAt < 7 * 86_400_000,
      };
    });
  },
});

/** A course workspace: the pathway, tick-off progress and linked study sets. */
export const getDetails = query({
  args: { courseId: v.id("courses") },
  handler: async (ctx, { courseId }) => {
    const userId = await requireUserId(ctx);
    const course = await ctx.db.get(courseId);
    if (!course || course.userId !== userId) return null;

    const sets = await ctx.db
      .query("studySets")
      .withIndex("by_course", (q) => q.eq("courseId", courseId))
      .order("desc")
      .collect();

    const ids = topicIds(course.pathway);
    return {
      course,
      completedCount: course.completedTopics.filter((id) => ids.has(id)).length,
      topicCount: countTopics(course.pathway),
      sets: sets
        .filter((set) => set.userId === userId)
        .map((set) => ({
          _id: set._id,
          title: set.title,
          topicId: set.topicId,
          // Older sets have no topicIds list; their single topic is the set.
          topicIds: set.topicIds ?? (set.topicId ? [set.topicId] : []),
          status: set.status,
          sourceType: set.sourceType,
          sourceLabel: set.sourceLabel,
          cardCount: set.cardCount,
          knownCount: set.knownCount,
          quizCount: set.quizCount,
          examCount: set.examCount,
          updatedAt: set.updatedAt,
        })),
      processingStale: buildStalled(course, Date.now()),
    };
  },
});

/**
 * Queues a batch of courses. The first build starts immediately and the rest
 * are staggered so a nine-course setup makes one Cognito request at a time
 * all at once.
 */
export const createMany = mutation({
  args: {
    level: v.string(),
    examBoard: v.string(),
    courses: v.array(
      v.object({
        subject: v.string(),
        // Each subject may sit with a different board. The top-level board is
        // the fallback for anything that omits one.
        examBoard: v.optional(v.string()),
        tier: v.optional(v.string()),
        variant: v.optional(v.string()),
        // Edexcel GCSE Religious Studies choices: route A or B, religion,
        // third paper (A) or the two Areas of Study (B).
        rsRoute: v.optional(v.string()),
        rsReligion: v.optional(v.string()),
        rsReligion2: v.optional(v.string()),
        rsSpec: v.optional(v.string()),
        rsSpec2: v.optional(v.string()),
      }),
    ),
  },
  handler: async (ctx, args) => {
    const userId = await requireUserId(ctx);
    await requireVerifiedUser(ctx, userId);

    const level = normalizeLevel(args.level);
    const defaultBoard = safeCourseLabel(args.examBoard);
    if (!level) {
      throw new Error("Choose your level first.");
    }

    // GCSE defaults to Higher. The picker sends this explicitly, but enforcing
    // it here keeps older clients and direct calls consistent. GCSE routes are
    // separate subjects now, so drop any legacy Triple/Combined variant.
    const defaultTier = level === "GCSE" ? "Higher" : undefined;
    // KS3 sits below GCSE and has no exam board or tier at all.
    const isKs3 = level === "KS3";
    const requested = args.courses
      .map((course) => ({
        subject: safeCourseLabel(course.subject),
        examBoard:
          isKs3
            ? "None"
            : safeCourseLabel(course.examBoard) || defaultBoard,
        tier: isKs3
          ? undefined
          : safeCourseLabel(course.tier) || defaultTier,
        variant:
          level === "GCSE" || isKs3
            ? undefined
            : safeCourseLabel(course.variant),
        rsRoute: isKs3 ? undefined : safeCourseLabel(course.rsRoute),
        rsReligion: isKs3 ? undefined : safeCourseLabel(course.rsReligion),
        rsReligion2: isKs3 ? undefined : safeCourseLabel(course.rsReligion2),
        rsSpec: isKs3 ? undefined : safeCourseLabel(course.rsSpec),
        rsSpec2: isKs3 ? undefined : safeCourseLabel(course.rsSpec2),
      }))
      .filter((course) => course.subject?.length ?? 0 > 0)
      .slice(0, MAX_COURSES_PER_SETUP);

    if (requested.length === 0) {
      throw new Error("Pick at least one course.");
    }
    if (requested.some((course) => !course.examBoard)) {
      throw new Error("Choose an exam board for every course.");
    }

    const existing = await ctx.db
      .query("courses")
      .withIndex("by_user_updated", (q) => q.eq("userId", userId))
      .collect();
    const signature = (course: {
      subject?: string | null;
      level?: string;
      examBoard?: string | null;
      variant?: string | null;
      tier?: string | null;
      rsRoute?: string | null;
      rsReligion?: string | null;
      rsReligion2?: string | null;
      rsSpec?: string | null;
      rsSpec2?: string | null;
    }) =>
      // Every RS choice is part of the identity: changing the main religion or
      // an Area of Study is a different pathway, not a duplicate.
      `${course.subject}|${course.level}|${course.examBoard}|${course.variant ?? ""}|${course.tier ?? ""}|${course.rsRoute ?? ""}|${course.rsReligion ?? ""}|${course.rsReligion2 ?? ""}|${course.rsSpec ?? ""}|${course.rsSpec2 ?? ""}`.toLowerCase();

    const known = new Set(
      existing.map((course) =>
        signature({
          subject: course.subject,
          level: course.level,
          examBoard: course.examBoard,
          variant: course.variant,
          tier: course.tier,
          rsRoute: course.rsRoute,
          rsReligion: course.rsReligion,
          rsReligion2: course.rsReligion2,
          rsSpec: course.rsSpec,
          rsSpec2: course.rsSpec2,
        }),
      ),
    );

    const now = Date.now();
    const ids: Id<"courses">[] = [];
    for (const course of requested) {
      const key = signature({ ...course, level });
      if (known.has(key)) continue;
      known.add(key);

      const courseId = await ctx.db.insert("courses", {
        userId,
        subject: course.subject!,
        level,
        examBoard: course.examBoard!,
        tier: course.tier,
        variant: course.variant,
        rsRoute: course.rsRoute,
        rsReligion: course.rsReligion,
        rsReligion2: course.rsReligion2,
        rsSpec: course.rsSpec,
        rsSpec2: course.rsSpec2,
        status: "queued",
        progress: "Queued",
        completedTopics: [],
        createdAt: now,
        updatedAt: now,
      });
      ids.push(courseId);
    }

    // Stagger server-side builds. They continue even if the student closes the
    // tab, and the course page updates reactively when each one finishes.
    for (const [index, courseId] of ids.entries()) {
      await ctx.scheduler.runAfter(index * 1_500, internal.ai.buildCoursePathway, {
        courseId,
      });
    }

    return { ids, queued: ids.length, skipped: requested.length - ids.length };
  },
});

/** Ticks a topic off as revised, or clears the tick. */
export const setTopicDone = mutation({
  args: {
    courseId: v.id("courses"),
    topicId: v.string(),
    done: v.boolean(),
  },
  handler: async (ctx, { courseId, topicId, done }) => {
    const userId = await requireUserId(ctx);
    const course = await requireOwner(
      await ctx.db.get(courseId),
      userId,
    ) as Doc<"courses">;
    if (!topicIds(course.pathway).has(topicId)) {
      throw new Error("That topic is not part of this pathway.");
    }

    const completed = new Set<string>(course.completedTopics);
    if (done) completed.add(topicId);
    else completed.delete(topicId);
    const now = Date.now();
    await ctx.db.patch(courseId, {
      completedTopics: [...completed],
      lastStudiedAt: now,
      updatedAt: now,
    });
  },
});

/**
 * A removed topic's set stays in the library but no longer claims a pathway
 * topic, so the course page does not show a "Study this topic" button for
 * something the student has deleted.
 */
async function unlinkTopicSets(
  ctx: MutationCtx,
  courseId: Id<"courses">,
  userId: Id<"users">,
  topicIds: Set<string>,
) {
  const sets = await ctx.db
    .query("studySets")
    .withIndex("by_course", (q) => q.eq("courseId", courseId))
    .collect();
  for (const set of sets) {
    if (set.userId !== userId) continue;
    const covered = set.topicIds ?? (set.topicId ? [set.topicId] : []);
    if (!covered.some((id) => topicIds.has(id))) continue;
    const remaining = covered.filter((id) => !topicIds.has(id));
    // A set that only covered removed sections is unlinked from the course but
    // stays in the library. A set that still covers at least one section keeps
    // its link and forgets the sections that no longer exist on the pathway.
    if (remaining.length === 0) {
      await ctx.db.patch(set._id, {
        courseId: undefined,
        topicId: undefined,
        topicIds: undefined,
      });
      continue;
    }
    await ctx.db.patch(set._id, {
      topicIds: remaining,
      topicId: remaining[0],
    });
  }
}

/**
 * Removes one topic the student does not study — the common case being an
 * anthology cluster or optional unit their school did not enter them for. The
 * pathway is the only thing edited, and a rebuild brings the topic back.
 */
export const removeTopic = mutation({
  args: { courseId: v.id("courses"), topicId: v.string() },
  handler: async (ctx, { courseId, topicId }) => {
    const userId = await requireUserId(ctx);
    const course = await requireOwner(
      await ctx.db.get(courseId),
      userId,
    ) as Doc<"courses">;
    const pathway = course.pathway;
    if (!pathway) throw new Error("This pathway is still being built.");

    const removed = pathway.units
      .flatMap<{ id: string; title: string }>((unit) => unit.topics)
      .find((topic) => topic.id === topicId);
    if (!removed) throw new Error("That topic is not part of this pathway.");

    const units = pathway.units
      .map((unit) => ({
        ...unit,
        topics: unit.topics.filter((topic) => topic.id !== topicId),
      }))
      .filter((unit) => unit.topics.length > 0);

    await ctx.db.patch(courseId, {
      pathway: { ...pathway, units },
      completedTopics: course.completedTopics.filter((id) => id !== topicId),
      updatedAt: Date.now(),
    });
    await unlinkTopicSets(ctx, courseId, userId, new Set([topicId]));
    return { title: removed.title };
  },
});

/** Removes a whole unit, such as a poetry cluster the student is not studying. */
export const removeUnit = mutation({
  args: { courseId: v.id("courses"), unitIndex: v.number() },
  handler: async (ctx, { courseId, unitIndex }) => {
    const userId = await requireUserId(ctx);
    const course = await requireOwner(
      await ctx.db.get(courseId),
      userId,
    ) as Doc<"courses">;
    const pathway = course.pathway;
    if (!pathway) throw new Error("This pathway is still being built.");

    const unit = pathway.units[unitIndex];
    if (
      !unit ||
      !Number.isInteger(unitIndex) ||
      unitIndex < 0 ||
      unitIndex >= pathway.units.length
    ) {
      throw new Error("That unit is not part of this pathway.");
    }

    const removedIds = new Set<string>(unit.topics.map((topic) => topic.id));
    await ctx.db.patch(courseId, {
      pathway: {
        ...pathway,
        units: pathway.units.filter((_: unknown, index: number) => index !== unitIndex),
      },
      completedTopics: course.completedTopics.filter((id) => !removedIds.has(id)),
      updatedAt: Date.now(),
    });
    await unlinkTopicSets(ctx, courseId, userId, removedIds);
    return { title: unit.title, topics: unit.topics.length };
  },
});

/** One pathway topic together with the unit it sits in. */
type PathwaySection = {
  unit: NonNullable<Doc<"courses">["pathway"]>["units"][number];
  topic: NonNullable<
    NonNullable<Doc<"courses">["pathway"]>["units"][number]["topics"]
  >[number];
};

/**
 * The most sections one set can cover. Twelve keeps the source text well inside
 * what the generator (and the screen that shows it) can handle.
 */
const MAX_SET_SECTIONS = 12;

/**
 * Creates the study set for one pathway section, or for a run of them. The
 * pathway already contains a summary, key points and exam skill, so those
 * become the source material for the normal summary/flashcards/quiz/exam
 * pipeline.
 *
 * `sections` is how many sections the set should cover, counting the chosen
 * topic first. It defaults to one and is clamped to what the pathway has left
 * after that topic, so asking for six near the end of a course never creates an
 * empty set.
 */
export const createTopicSet = mutation({
  args: {
    courseId: v.id("courses"),
    topicId: v.string(),
    sections: v.optional(v.number()),
  },
  handler: async (ctx, { courseId, topicId, sections }) => {
    const userId = await requireUserId(ctx);
    const course = await requireOwner(
      await ctx.db.get(courseId),
      userId,
    ) as Doc<"courses">;
    if (!course.pathway) throw new Error("This pathway is still being built.");

    // Flatten the pathway into reading order so "sections" always means the
    // next topics on the student's route, even across a unit boundary.
    const outline: PathwaySection[] = course.pathway.units.flatMap((unit) =>
      unit.topics.map((topic) => ({ unit, topic })),
    );
    const startIndex = outline.findIndex((entry) => entry.topic.id === topicId);
    if (startIndex === -1) {
      throw new Error("That topic is not part of this pathway.");
    }

    const requested = Number.isFinite(sections) ? Math.floor(sections ?? 1) : 1;
    const count = Math.min(
      Math.max(1, requested),
      MAX_SET_SECTIONS,
      outline.length - startIndex,
    );
    const chosen = outline.slice(startIndex, startIndex + count);

    // Reuse an existing set that covers exactly these sections, so repeated
    // taps never create duplicate decks. Sets built before sections existed
    // only have `topicId`, which is treated as a one-section set.
    const existing = await ctx.db
      .query("studySets")
      .withIndex("by_course", (q) => q.eq("courseId", courseId))
      .collect();
    const wanted = chosen.map((entry) => entry.topic.id).join("|");
    const match = existing.find((set) => {
      if (set.userId !== userId) return false;
      const covered = set.topicIds ?? (set.topicId ? [set.topicId] : []);
      if (covered.join("|") === wanted) return true;
      // A caller that did not ask for a length (the timetable opening a session)
      // just wants the set for this topic, whichever build produced it.
      return sections === undefined && covered.includes(topicId);
    });
    if (match) return { setId: match._id, created: false, sections: chosen.length };

    const notes = buildTopicNotes(course, chosen);
    const first = chosen[0]!.topic;
    // One section keeps the topic's own name; a longer set is named after the
    // first section so the library row still says what it covers.
    const title =
      chosen.length === 1
        ? safeCourseLabel(first.title)
        : safeCourseLabel(`${first.title} + ${chosen.length - 1} more`);

    const now = Date.now();
    const setId = await ctx.db.insert("studySets", {
      userId,
      title: title || "Revision topic",
      notes,
      sourceType: "text",
      sourceLabel:
        chosen.length === 1
          ? "Course pathway"
          : `Course pathway · ${chosen.length} sections`,
      course: safeCourseLabel(course.subject),
      examBoard: safeCourseLabel(course.examBoard),
      level: safeCourseLabel(course.level),
      courseId,
      topicId,
      topicIds: chosen.map((entry) => entry.topic.id),
      sourceImageIds: [],
      status: "queued",
      progress: "Queued",
      cardCount: 0,
      quizCount: 0,
      examCount: 0,
      targetCardCount: BUILD_DEFAULTS.cards,
      targetQuizCount: BUILD_DEFAULTS.quiz,
      targetExamCount: BUILD_DEFAULTS.exam,
      knownCount: 0,
      updatedAt: now,
    });

    await ctx.db.patch(courseId, { lastStudiedAt: now, updatedAt: now });
    return { setId, created: true, sections: chosen.length };
  },
});

/**
 * Builds the brief for a pathway set from the stored pathway: what the set must
 * cover, not the content itself. The generator writes the subject content from
 * this scope (see PATHWAY_MATERIAL_RULES in ai.ts), so the brief deliberately
 * leaves out exam technique and commentary about the course.
 *
 * More than one section is written under numbered headings, so the generated
 * material keeps each topic distinct instead of blending them together.
 */
function buildTopicNotes(
  course: Doc<"courses">,
  sections: PathwaySection[],
): string {
  const parts = [
    `Course: ${course.level} ${course.subject}`,
    `Exam board: ${course.examBoard}${course.variant ? ` · ${course.variant}` : ""}${course.tier ? ` · ${course.tier}` : ""}`,
    course.poetryTheme ? `Poetry theme: ${course.poetryTheme}` : "",
    "",
    "Syllabus scope for this set:",
  ];

  // The topic's exam skill is technique, not subject content: sending it to the
  // generator produces cards about exam craft instead of the topic.
  sections.forEach(({ unit, topic }, index) => {
    const heading =
      sections.length === 1
        ? `Topic: ${topic.title}`
        : `Section ${index + 1}: ${topic.title}`;
    parts.push(
      "",
      `${heading}${topic.specReference ? ` (specification ${topic.specReference})` : ""}`,
      `Unit: ${unit.title}`,
      topic.summary,
      ...(topic.keyPoints.length > 0 ? ["Covers:"] : []),
      ...topic.keyPoints.map((point) => `- ${point}`),
    );
  });

  return parts.filter((line) => line !== "").join("\n");
}

/**
 * Stores the Cognito links read for an older course. It only fills fields the
 * pathway is missing, so a backfill can never rewrite the topic map itself.
 */
export const attachCognitoLinks = internalMutation({
  args: {
    courseId: v.id("courses"),
    sourceUrl: v.optional(v.string()),
    syncedAt: v.number(),
    papers: v.optional(
      v.array(
        v.object({
          label: v.string(),
          topicIds: v.array(v.string()),
        }),
      ),
    ),
  },
  handler: async (ctx, { courseId, sourceUrl, papers, syncedAt }) => {
    const course = await ctx.db.get(courseId);
    if (!course?.pathway) return;
    await ctx.db.patch(courseId, {
      pathway: {
        ...course.pathway,
        ...(course.pathway.sourceUrl
          ? {}
          : sourceUrl
            ? { sourceUrl }
            : {}),
        ...(course.pathway.papers ? {} : papers ? { papers } : {}),
        cognitoSyncedAt: syncedAt,
      },
    });
  },
});

/**
 * Deletes the pathway, not the student's work. Study sets built from its topics
 * stay in the library and simply lose their course link.
 */
export const remove = mutation({
  args: { courseId: v.id("courses") },
  handler: async (ctx, { courseId }) => {
    const userId = await requireUserId(ctx);
    const course = await requireOwner(
      await ctx.db.get(courseId),
      userId,
    ) as Doc<"courses">;

    const sets = await ctx.db
      .query("studySets")
      .withIndex("by_course", (q) => q.eq("courseId", courseId))
      .collect();
    for (const set of sets) {
      if (set.userId === userId) {
        await ctx.db.patch(set._id, {
          courseId: undefined,
          topicId: undefined,
          topicIds: undefined,
        });
      }
    }
    await ctx.db.delete(courseId);
  },
});

